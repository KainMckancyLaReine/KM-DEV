/* --- eenkleurige merken --- */
function mono(name, size, opt){
    opt = opt || {};
    var m = MONO[name];
    if(!m) return '';
    var fill = opt.color || (opt.auto ? 'currentColor' : (m.hex === '#000000' ? 'currentColor' : m.hex));
    return '<svg class="km-logo km-logo-' + name + '" viewBox="0 0 24 24" width="' + size + '" height="' + size + '" ' +
        'role="img" aria-label="' + m.title + '" style="display:block;' + (opt.style||'') + '">' +
        '<path d="' + m.path + '" fill="' + fill + '"/></svg>';
}

